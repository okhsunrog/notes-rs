pub fn export_bindings(path: impl AsRef<std::path::Path>) -> Result<(), String> {
    specta_builder()
        .export(
            specta_typescript::Typescript::default()
                .header("/* eslint-disable */\n// Generated by tauri-specta. Do not edit.\n"),
            path,
        )
        .map_err(|error| error.to_string())
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    init_tracing();

    let specta_builder = specta_builder();

    #[cfg(debug_assertions)]
    export_bindings("../src/lib/bindings.ts").expect("exporting TypeScript bindings");

    let invoke_handler = specta_builder.invoke_handler();
    let builder = tauri::Builder::default().plugin(tauri_plugin_opener::init());

    #[cfg(not(target_os = "android"))]
    let builder = builder.plugin(tauri_plugin_dialog::init());

    #[cfg(target_os = "android")]
    let builder = builder
        .plugin(tauri_plugin_android_fs::init())
        .plugin(tauri_plugin_mobile_system::init());

    // Development-only bridge for MCP-powered UI inspection and automation.
    // Restrict it to localhost; release builds do not register the plugin.
    #[cfg(all(debug_assertions, not(mobile)))]
    let builder = builder.plugin(
        tauri_plugin_mcp_bridge::Builder::new()
            .bind_address("127.0.0.1")
            .build(),
    );

    builder
        .setup(move |app| {
            specta_builder.mount_events(app);
            let handle = app.handle().clone();
            let data_dir = app.path().app_data_dir().expect("resolving app data dir");
            std::fs::create_dir_all(&data_dir).expect("creating data dir");

            // Desktop launches don't inherit shell env. Load .env from the app
            // data dir if present so API keys configured by the user survive
            // double-click launches. Missing file is fine.
            let env_path = data_dir.join(".env");
            match dotenvy::from_path(&env_path) {
                Ok(()) => tracing::info!(?env_path, "loaded .env"),
                Err(dotenvy::Error::Io(e)) if e.kind() == std::io::ErrorKind::NotFound => {}
                Err(e) => tracing::warn!(?env_path, error = %e, "failed to load .env"),
            }
            #[cfg(not(mobile))]
            if let Err(error) = settings::apply_saved_window_preferences(&handle) {
                tracing::warn!(%error, "failed to apply saved window preferences");
            }

            let db_path = data_dir.join("notes.db");
            let sync_credentials = settings::sync_credentials(&handle);
            let server_mode = matches!(sync_credentials, Ok(Some(_)));
            let remote_ai = sync_credentials
                .as_ref()
                .ok()
                .and_then(Option::as_ref)
                .map(|(server_url, token)| {
                    notes_sync::HttpTransport::new(server_url.clone(), token.clone())
                })
                .transpose()?;
            let configured_settings = settings::load(&handle);
            let sync_runtime = sync::SyncRuntime::disabled();
            let sync_status = sync_runtime.status.clone();
            app.manage(sync_runtime);

            // Register the readiness flag immediately so the frontend can
            // poll/listen instead of invoking commands that would otherwise
            // fail with an opaque "state not managed" error during the
            // (slow, first-run) embedder model download.
            let startup = Arc::new(RwLock::new(commands::StartupStatus::Starting {
                message: "Opening database and loading search providers…".into(),
            }));
            handle.manage(commands::Startup {
                status: startup.clone(),
            });

            tauri::async_runtime::spawn(async move {
                let initialize = async {
                    let (embedder, reranker, id, ndims) = if server_mode {
                        let settings = configured_settings?;
                        let fallback_ndims = settings
                            .embedding_ndims
                            .context("embedding dimensions are required in server mode")?
                            as usize;
                        let fallback_id = format!(
                            "{}:{}",
                            settings.embedding_provider, settings.embedding_model
                        );
                        let (id, ndims) = match remote_ai.as_ref() {
                            Some(transport) => match transport.info().await {
                                Ok(info) => {
                                    if !info.ai_enabled {
                                        anyhow::bail!("the configured sync server has AI disabled");
                                    }
                                    (info.embedding_provider_id, info.embedding_dimensions)
                                }
                                Err(error) => {
                                    tracing::warn!(%error, "server info unavailable; opening the offline cache with saved embedding metadata");
                                    (fallback_id, fallback_ndims)
                                }
                            },
                            None => (fallback_id, fallback_ndims),
                        };
                        tracing::info!(embedder = %id, ndims, "using server-owned AI");
                        (None, None, id, ndims)
                    } else {
                        let embedder = embed::make_embedder()?;
                        let id = embedder.id();
                        let ndims = embedder.ndims();
                        let reranker = embed::make_reranker()?;
                        tracing::info!(embedder = %id, ndims, "local AI providers loaded");
                        (Some(embedder), Some(reranker), id, ndims)
                    };
                    let conn = db::open(&db_path, &id, ndims).await?;
                    anyhow::Ok((conn, embedder, reranker))
                };

                match initialize.await {
                    Ok((conn, embedder, reranker)) => {
                        let background_paused = Arc::new(AtomicBool::new(false));
                        if let Some(embedder) = &embedder {
                            let embedding_event_handle = handle.clone();
                            embed::spawn_worker(
                                conn.clone(),
                                embedder.clone(),
                                Arc::new(move || {
                                    commands::emit_domain(
                                        &embedding_event_handle,
                                        commands::DomainEvent::BackgroundStatusChanged,
                                    );
                                }),
                                background_paused.clone(),
                            );
                        }
                        if !server_mode && notes_ai::config::entity_extraction_enabled() {
                            let extractor = Arc::new(extract::EntityExtractor::new());
                            let event_handle = handle.clone();
                            let status_event_handle = handle.clone();
                            extract::spawn_worker(
                                conn.clone(),
                                extractor,
                                Arc::new(move || {
                                    commands::emit_domain(
                                        &event_handle,
                                        commands::DomainEvent::GraphChanged {
                                            node_uuids: Vec::new(),
                                        },
                                    );
                                }),
                                Arc::new(move || {
                                    commands::emit_domain(
                                        &status_event_handle,
                                        commands::DomainEvent::BackgroundStatusChanged,
                                    );
                                }),
                                background_paused.clone(),
                            );
                        } else {
                            tracing::info!("automatic entity extraction is disabled");
                        }
                        handle.manage(commands::AppState {
                            conn: conn.clone(),
                            embedder,
                            reranker,
                            remote_ai,
                            background_paused,
                            chat_cancellations: Arc::new(std::sync::Mutex::new(
                                std::collections::HashMap::new(),
                            )),
                        });
                        match sync_credentials {
                            Ok(Some((server_url, token))) => sync::spawn_worker(
                                handle.clone(),
                                conn.clone(),
                                server_url,
                                token,
                                data_dir.clone(),
                                sync_status,
                            ),
                            Ok(None) => {}
                            Err(error) => {
                                tracing::error!(%error, "sync configuration is invalid");
                                *sync_status.write().unwrap_or_else(|e| e.into_inner()) =
                                    sync::SyncStatus {
                                        state: sync::SyncConnectionState::Error,
                                        server_url: None,
                                        last_server_seq: 0,
                                        pending_operations: 0,
                                        message: Some(error.to_string()),
                                    };
                            }
                        }
                        *startup.write().unwrap_or_else(|e| e.into_inner()) =
                            commands::StartupStatus::Ready;
                        let _ = handle.emit("app:ready", ());
                        tracing::info!(?db_path, "notes-rs ready");
                    }
                    Err(error) => {
                        let message = format!("{error:#}");
                        tracing::error!(%message, "notes-rs startup failed");
                        *startup.write().unwrap_or_else(|e| e.into_inner()) =
                            commands::StartupStatus::Error {
                                message: message.clone(),
                            };
                        let _ = handle.emit("app:startup-error", message);
                    }
                }
            });

            Ok(())
        })
        .invoke_handler(invoke_handler)
        .run(tauri::generate_context!())
        .expect("error while running tauri application");
}

#[cfg(not(target_os = "android"))]
fn init_tracing() {
    tracing_subscriber::fmt()
        .with_max_level(tracing::Level::INFO)
        .init();
}

#[cfg(target_os = "android")]
fn init_tracing() {
    use tracing_logcat::{LogcatMakeWriter, LogcatTag};

    let writer = LogcatMakeWriter::new(LogcatTag::Fixed("notes-rs".into()))
        .expect("creating Android logcat writer");
    tracing_subscriber::fmt()
        .with_ansi(false)
        .with_target(true)
        .with_max_level(tracing::Level::INFO)
        .with_writer(writer)
        .init();
}
